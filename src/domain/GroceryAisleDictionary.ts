const dictionary: ReadonlyMap<string, GroceryAisle> = new Map(
  Object.entries(entries).flatMap(([aisle, names]) =>
    names.map((name) => [name, aisle as GroceryAisle] as const),
  ),
)

// Words naming a part of the ingredient rather than the ingredient, so
// "garlic cloves" is filed as garlic, not the spice.
const partWords = new Set([
  "breast",
  "breasts",
  "clove",
  "cloves",
  "fillet",
  "fillets",
  "floret",
  "florets",
  "leaf",
  "leaves",
  "sprig",
  "sprigs",
  "stalk",
  "stalks",
  "thigh",
  "thighs",
  "zest",
])

const singulars = (word: string): ReadonlyArray<string> => [
  word,
  word.replace(/ies$/, "y"),
  word.replace(/oes$/, "o"),
  word.replace(/es$/, ""),
  word.replace(/s$/, ""),
]

// The dictionary's aisle for an ingredient name, if any. Only the part
// before a comma counts, and parentheses are dropped.
export const dictionaryAisle = (name: string): GroceryAisle | null => {
  const words = name
    .split(",")[0]
    .toLowerCase()
    .replace(/\([^)]*\)/g, " ")
    .replace(/[^\p{L}\s'-]/gu, " ")
    .split(/\s+/)
    .filter((word) => word.length > 0)
  if (words[0] === "frozen") return "Frozen Foods"
  if (words[0] === "canned" || words[0] === "tinned") {
    return "Canned & Jar Goods"
  }
  if (words.length > 1 && partWords.has(words[words.length - 1])) {
    words.pop()
  }
  if (words.length === 0) return null
  const last = singulars(words[words.length - 1])
  for (let i = 0; i < words.length; i++) {
    const head = words.slice(i, -1)
    for (const word of last) {
      const aisle = dictionary.get([...head, word].join(" "))
      if (aisle !== undefined) return aisle
    }
  }
  return null
}
